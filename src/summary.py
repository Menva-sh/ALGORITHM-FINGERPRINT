"""Write results/summary.md: the key tables, built only from the CSVs in results/.

Every number in the summary comes from a results file regenerated by `python -m
src.reproduce`; nothing is typed in by hand.

Run:  python -m src.summary
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

from src.config import PROJECT_ROOT, load_config


def md_table(df: pd.DataFrame, digits: int = 3) -> str:
    """Plain markdown table (no extra dependency)."""
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else f"{v:.{digits}f}")
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows])


def build(res: Path, data: Path) -> str:
    """Summary markdown from the result CSVs."""
    ds = pd.read_csv(data, usecols=["graph_id", "best_time", "tie"])
    parts = ["# Results summary", "",
             "_Generated by `python -m src.summary` from the files in `results/`. "
             "Do not edit by hand._", "",
             "## Dataset", "",
             f"{ds['graph_id'].nunique()} graphs, {len(ds)} queries, tie rate "
             f"{ds['tie'].mean():.3f}.", "",
             md_table(ds["best_time"].value_counts(normalize=True).rename("share")
                      .rename_axis("fastest algorithm").reset_index()), ""]

    m = pd.read_csv(res / "model_results.csv", index_col=0)
    cols = ["accuracy", "regret_mean", "regret_p95", "net_s", "saved_vs_best_fixed",
            "saved_vs_best_fixed_amortised"]
    parts += ["## Selectors vs baselines (Tier-0 features, held-out graphs)", "",
              md_table(m[cols].rename_axis("method").reset_index()), ""]

    t = pd.read_csv(res / "tiers_summary.csv")
    parts += ["## Feature tiers (contribution 1)", "",
              md_table(t[["tier_set", "model", "overhead_ms", "accuracy", "regret_mean",
                          "net_rel_best_fixed", "pareto_regret"]]), ""]

    p = pd.read_csv(res / "probing_summary.csv")
    parts += ["## Probing features (contribution 2)", "",
              md_table(p[["static_set", "k", "model", "probe_ms", "accuracy", "regret_mean",
                          "accuracy_gain_pp_per_ms", "net_rel_best_fixed"]]), ""]

    u = pd.read_csv(res / "uncertainty_abstention.csv")
    c = pd.read_csv(res / "uncertainty_calibration.csv")
    parts += ["## Uncertainty (contribution 3)", "", md_table(c, 4), "",
              md_table(u[["model", "target_coverage", "empirical_coverage", "share_sure",
                          "policy", "regret_mean", "net_rel_best_fixed"]]), ""]

    d = pd.read_csv(res / "explain_distillation.csv")
    tb = pd.read_csv(res / "explain_textbook.csv")
    parts += ["## Explainability (contribution 4)", "", md_table(d), "", md_table(tb), "",
              "Rules: see `results/rules_T0.txt` and `results/rules_T0+1+2+3.txt`.", ""]

    s = pd.read_csv(res / "shift_size_summary.csv")
    lab = pd.read_csv(res / "shift_labels.csv")
    real = pd.read_csv(res / "shift_real.csv")
    parts += ["## Strength checks (Stage 9)", "", "### Size shift", "",
              md_table(s[["shift", "reference", "feature_set", "method", "regret_reference",
                          "regret_shifted", "regret_change", "net_rel_best_fixed_shifted"]]),
              "", "### Time vs op-count labels", "", md_table(lab), "",
              "### Synthetic -> real graphs", "", md_table(real), ""]
    return "\n".join(parts)


def main() -> None:
    cfg = load_config()
    res = PROJECT_ROOT / cfg["paths"]["results"]
    out = res / "summary.md"
    out.write_text(build(res, PROJECT_ROOT / cfg["paths"]["dataset"]), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
